// The commit-msg hook, run for real on sample messages: what it refuses, and — as important
// in a repository whose subject IS models and providers — what it must let through.
import { describe, it, expect } from "vitest";
import { spawnSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HOOK = join(dirname(fileURLToPath(import.meta.url)), "..", "..", ".githooks", "commit-msg");
const dir = mkdtempSync(join(tmpdir(), "commit-msg-hook-"));
let n = 0;

function run(message: string): { ok: boolean; said: string } {
  const file = join(dir, `msg-${n++}`);
  writeFileSync(file, message);
  const r = spawnSync("sh", [HOOK, file], { encoding: "utf8" });
  return { ok: r.status === 0, said: r.stderr };
}

describe.skipIf(process.platform === "win32")("commit-msg — one author, no trace of a tool", () => {
  it("refuses an assistant co-author trailer, whatever its casing or address", () => {
    for (const trailer of [
      "Co-Authored-By: Claude <noreply@anthropic.com>",
      "co-authored-by: GitHub Copilot <copilot@github.com>",
      "  Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
      "Co-Authored-By: some-tool[bot] <1+some-tool[bot]@users.noreply.github.com>",
    ]) {
      const r = run(`fix(store): seal the session again after a keychain miss\n\n${trailer}\n`);
      expect(r.ok, trailer).toBe(false);
      expect(r.said).toContain("co-author");
    }
  });

  it("refuses a « generated with » line, a tool's signature and a session link", () => {
    for (const body of [
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "Generated with Claude Code",
      "written by an AI assistant",
      "Created by ChatGPT",
      "https://claude.ai/code/session_01ABC",
    ]) {
      expect(run(`feat(ui): a reload offer when the window stops\n\n${body}\n`).ok, body).toBe(false);
    }
  });

  it("lets a human co-author through, and a commit ABOUT a provider, a model or a guide file", () => {
    for (const message of [
      "feat(llm): add the claude-sonnet pricing row\n",
      "docs: split the root CLAUDE.md, the map stays under 200 lines\n",
      "fix(proxy): the Anthropic-compatible endpoint keeps tool_use ids\n",
      "fix(llm): OpenAI and Gemini share one SSE reader\n\nCo-Authored-By: Jeanne Martin <jeanne@example.org>\n",
      "feat(mcp): tools generated by the catalogue script are sorted\n",
      "chore: reword\n# Co-Authored-By: Claude <noreply@anthropic.com>\n# (a comment line git strips)\n",
    ]) {
      const r = run(message);
      expect(r.ok, `${message}\n${r.said}`).toBe(true);
    }
  });

  it("still refuses a retired name", () => {
    const retired = ["kav", "iar"].join("");
    expect(run(`chore: rename ${retired} leftovers\n`).ok).toBe(false);
  });
});
