#!/usr/bin/env node
/**
 * `src/features/console/tokens.css`, generated from the ONE home of the design tokens:
 * `packages/ui/src/styles.css` and the sheets it imports. The console page must not carry a
 * second copy of a colour — the terminal's `lib/ui/palette.ts` already learned that lesson,
 * and guards it with a parity test that READS the source. This is the same discipline for a
 * page instead of a pill.
 *
 * Only what the page actually references is emitted, resolved transitively: a token whose
 * value names another token pulls that one in too. The result is a few dozen declarations
 * rather than the product's several hundred.
 *
 *   node scripts/gen-console-tokens.mjs            # write
 *   node scripts/gen-console-tokens.mjs --check    # exit 1 on drift (the test uses this)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const UI = resolve(here, "../../../packages/ui/src");
const PAGE = join(here, "../src/features/console/index.html");
const OUT = join(here, "../src/features/console/tokens.css");

/** Every stylesheet the product's entry pulls in, in order — plus the entry itself. */
function sheets() {
  const entry = readFileSync(join(UI, "styles.css"), "utf8");
  const imported = [...entry.matchAll(/@import\s+"(\.\/[^"]+)"/g)].map((m) => m[1]);
  const out = [entry];
  for (const rel of imported) {
    try {
      out.push(readFileSync(join(UI, rel), "utf8"));
    } catch {
      // A sheet that moved is not this script's business to repair; the parity test will
      // fail loudly if a token it needs went with it.
    }
  }
  return out;
}

/** `--name: value;` declarations, per selector we care about. `:root` is the light theme. */
function declarations(css, selector) {
  const out = new Map();
  const re = new RegExp(`${selector.replace(/[[\]"]/g, "\\$&")}\\s*\\{([^}]*)\\}`, "g");
  for (const block of css.matchAll(re)) {
    for (const d of block[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out.set(d[1], d[2].trim());
  }
  return out;
}

function collect(selector) {
  const all = new Map();
  for (const css of sheets()) for (const [k, v] of declarations(css, selector)) all.set(k, v);
  return all;
}

/** Close over `var(--x)` references until nothing new is pulled in. */
function closure(wanted, light, dark) {
  const keep = new Set();
  const queue = [...wanted];
  while (queue.length) {
    const name = queue.pop();
    if (!name || keep.has(name)) continue;
    const value = light.get(name) ?? dark.get(name);
    if (value === undefined) continue;
    keep.add(name);
    for (const ref of [light.get(name), dark.get(name)]) {
      if (!ref) continue;
      for (const m of ref.matchAll(/var\((--[\w-]+)/g)) queue.push(m[1]);
    }
  }
  return keep;
}

const page = readFileSync(PAGE, "utf8");
const used = new Set([...page.matchAll(/var\((--[\w-]+)/g)].map((m) => m[1]));
// The page builds `--cav-<section>` names at runtime, so no `var(--cav-…)` literal appears
// for them: take every section token the product defines.
const light = collect(":root");
const dark = collect('[data-theme="dark"]');
for (const name of [...light.keys(), ...dark.keys()]) if (name.startsWith("--cav-")) used.add(name);

const keep = [...closure(used, light, dark)].sort();
const block = (map, selector) => {
  const rows = keep.filter((k) => map.has(k)).map((k) => `  ${k}: ${map.get(k)};`);
  return rows.length ? `${selector} {\n${rows.join("\n")}\n}\n` : "";
};

const css =
  `/* GENERATED by scripts/gen-console-tokens.mjs — do not edit.\n` +
  `   Source: packages/ui/src/styles.css and the sheets it imports (the one home of these\n` +
  `   values). \`tokens.test.ts\` re-runs the extraction and fails on drift. */\n` +
  `${block(light, ":root")}\n${block(dark, '[data-theme="dark"]')}`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== css) {
    console.error("console tokens are stale — run: node scripts/gen-console-tokens.mjs");
    process.exit(1);
  }
  console.log(`✓ console tokens match the design system (${keep.length} declarations)`);
} else {
  writeFileSync(OUT, css);
  console.log(`wrote ${OUT} — ${keep.length} declarations`);
}
